// Real pinned Decap editor with an isolated in-memory backend. No GitHub writes.
import {chromium} from 'playwright';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
import {start} from './serve.mjs';
import {fileURLToPath} from 'node:url';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const root=fileURLToPath(new URL('..',import.meta.url));process.chdir(root);
const out=process.env.ARTICLE_EDITOR_RESULTS || join(tmpdir(),'photografik-article-editor-check');await mkdir(out,{recursive:true});
if(!process.env.DECAP_TEST_BUNDLE)throw new Error('Set DECAP_TEST_BUNDLE to the official pinned decap-cms bundle; its SRI is verified before use. See docs/field-notes-image-layout.md.');
const bundle=await readFile(process.env.DECAP_TEST_BUNDLE);
assert.equal('sha384-'+createHash('sha384').update(bundle).digest('base64'),JSON.parse(await readFile('src/admin/decap.json','utf8')).integrity);
const server=await start(0),base='http://127.0.0.1:'+server.address().port;
const browser=await chromium.launch({channel:'chrome'});const page=await browser.newPage({viewport:{width:1440,height:1000}});page.setDefaultTimeout(15000);
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
const body='## Starting point\n\nFirst paragraph with **bold** and [a link](/contact).\n\n![Portrait](/v/ph-revivaluxe-portrait.webp "Caption travels with the image")\n\n## Next section\n\nThe later paragraph must stay exactly the same.\n\n![Another view](/v/ph-revivaluxe-portrait.webp "Second caption")';
await page.route('**/*',async route=>{const u=new URL(route.request().url());if(u.origin!==base)return route.abort();if(u.pathname==='/decap.js')return route.fulfill({contentType:'text/javascript',body:bundle});return route.continue();});
const html=(await readFile('dist/admin/index.html','utf8')).replace(/https:\/\/unpkg.com\/decap-cms@[^\"]+\/dist\/decap-cms.js/,'/decap.js');
await page.route(base+'/admin/',r=>r.fulfill({contentType:'text/html',body:html}));
const config=await readFile('dist/admin/config.js','utf8');
const patch=`\nwindow.PHOTOGRAFIK_CMS_CONFIG.backend.name='test-repo';window.PHOTOGRAFIK_CMS_CONFIG.local_backend=false;window.PHOTOGRAFIK_CMS_CONFIG.collections=window.PHOTOGRAFIK_CMS_CONFIG.collections.filter(c=>c.name==='field-notes').map(c=>({...c,fields:[{name:'title',label:'Title',widget:'string',default:'Drag image check'},{name:'published',label:'Show on site',widget:'boolean',default:false}, {...c.fields.find(f=>f.name==='body'),default:${JSON.stringify(body)}}]}));`;
await page.route(base+'/admin/config.js*',r=>r.fulfill({contentType:'text/javascript',body:config+patch}));
await page.goto(base+'/admin/#/collections/field-notes/new');
const login=page.getByRole('button',{name:/Login|Log in/i});if(await login.count())await login.first().click();
await page.getByRole('button',{name:'Arrange images',exact:true}).waitFor({timeout:30000});
console.log('Native writing control',await page.locator('[contenteditable=true]').count());
await page.getByRole('button',{name:'Arrange images',exact:true}).click();
assert.equal(await page.getByRole('button',{name:'Move image: Portrait',exact:true}).getAttribute('draggable'),'true');
const handle=page.getByRole('button',{name:'Move image: Portrait',exact:true});
await handle.scrollIntoViewIfNeeded();const hb=await handle.boundingBox();
await page.mouse.move(hb.x+hb.width/2,hb.y+hb.height/2);await page.mouse.down();
await page.mouse.move(hb.x+hb.width/2+15,hb.y+hb.height/2+15,{steps:6});
const destination=page.locator('[data-article-gap]').last();
await page.getByRole('button',{name:'Place image at the end of the article',exact:true}).waitFor();
await destination.scrollIntoViewIfNeeded();const db=await destination.boundingBox();
await page.mouse.move(db.x+db.width/2,db.y+db.height/2,{steps:16});await page.mouse.up();
console.log('Drag status:',await page.locator('.pgk-article-status').innerText());
await page.screenshot({path:out+'/native-drag-attempt.png'});
await page.getByRole('status').filter({hasText:'Image moved.'}).waitFor();
const labels=await page.locator('.pgk-article-image__label').allTextContents();assert.deepEqual(labels,['Another view','Portrait']);
await page.screenshot({path:out+'/native-drag-desktop.png'});
await page.getByRole('button',{name:'Undo image change',exact:true}).click();assert.deepEqual(await page.locator('.pgk-article-image__label').allTextContents(),['Portrait','Another view']);
await page.getByRole('button',{name:'Write',exact:true}).click();
await page.locator('[contenteditable=true]').waitFor();
const writeText=await page.locator('[contenteditable=true]').innerText();assert.ok(writeText.includes('First paragraph'));assert.ok(writeText.includes('The later paragraph'));
console.log('Native drag, undo, and writing mode passed');
await page.getByRole('button',{name:'Arrange images',exact:true}).click();
await page.setViewportSize({width:390,height:844});
await page.getByRole('button',{name:'Move image: Portrait',exact:true}).press('Enter');
await page.getByRole('button',{name:'Place image at the end of the article',exact:true}).press('Enter');
await page.getByRole('status').filter({hasText:'Image moved.'}).waitFor();
assert.deepEqual(await page.locator('.pgk-article-image__label').allTextContents(),['Another view','Portrait']);
assert.equal(await page.locator('.pgk-article-editor').evaluate(el=>el.scrollWidth>el.clientWidth+1),false);
await page.screenshot({path:out+'/native-placement-phone.png'});
await page.getByRole('button',{name:'Save',exact:true}).click();
await page.getByText('Save now',{exact:true}).click();
await page.waitForURL(/#\/collections\/field-notes\/entries\/drag-image-check/,{timeout:30000});
await page.getByRole('link',{name:/Writing in Field Notes collection/}).click();
await page.getByRole('link',{name:/Drag image check/}).click();
await page.getByRole('button',{name:'Arrange images',exact:true}).click();
assert.deepEqual(await page.locator('.pgk-article-image__label').allTextContents(),['Another view','Portrait']);
await page.setViewportSize({width:1440,height:1000});
await page.frameLocator('#preview-pane').getByText('Draft, not published.',{exact:true}).waitFor();
assert.ok((await page.locator('.pgk-article-image__caption').allTextContents()).includes('Caption travels with the image'));
console.log('Native fixture Save, reopen and draft isolation passed');
await page.screenshot({path:out+'/native-saved-reopened.png'});
assert.equal(errors.length,0,errors.join('\n'));
await writeFile(out+'/native-editor.json',JSON.stringify({backend:'isolated Decap test-repo; no GitHub writes',actualBundle:'3.16.3',sriVerified:true,nativeMouseDrag:true,undo:true,writeMode:true,phoneKeyboardPlacement:true,savedAndReopened:true,draftPreserved:true,errors},null,2));
await browser.close();server.close();
